import assert from 'node:assert/strict';
import {readFileSync} from 'node:fs';
import {matchingCountries,addCountries,removeCountries,selectedCountriesFirst} from '../lib/selection.ts';
const countries=JSON.parse(readFileSync(new URL('../lib/countries.json',import.meta.url)));
const empty={developingRegion:'',developmentGroup:'',geographicalRegion:''};
assert.equal(matchingCountries(countries,'',empty).length,195);
const eastAsia=matchingCountries(countries,'',{...empty,geographicalRegion:'Eastern Asia'});
assert.ok(eastAsia.some(country=>country.code==='KOR'));
assert.ok(!eastAsia.some(country=>country.code==='USA'));
const intersection=matchingCountries(countries,'',{...empty,geographicalRegion:'Eastern Asia',developmentGroup:'Very High'});
assert.ok(intersection.length>0 && intersection.length<eastAsia.length);
assert.ok(intersection.every(country=>country.geographicalRegion==='Eastern Asia' && country.developmentGroup==='Very High'));
const developing=matchingCountries(countries,'',{...empty,developingRegion:'Arab States'});
assert.equal(developing.length,20);
assert.deepEqual(matchingCountries(countries,'  kOrEa  ',empty).map(country=>country.code).sort(),['KOR','PRK']);
const added=addCountries(['USA',eastAsia[0].code],eastAsia);
assert.equal(added.size,eastAsia.length+1);
assert.ok(added.has('USA'));
assert.deepEqual([...removeCountries(added,eastAsia)],['USA']);
assert.equal(addCountries([],countries).size,195);
assert.equal(removeCountries(added,countries).size,0);
console.log('Passed country selection: all, geographic/developing/development groups, intersecting facets, search, additive deduplication and deselection.');

const input=[{code:"Z",name:"Zimbabwe"},{code:"A",name:"Albania"},{code:"B",name:"Brazil"},{code:"C",name:"Canada"}];
assert.deepEqual(selectedCountriesFirst(input,["Z","B"]).map(country=>country.code),["B","Z","A","C"]);
assert.deepEqual(selectedCountriesFirst(input,new Set(["C"])).map(country=>country.code),["C","A","B","Z"]);
assert.deepEqual(input.map(country=>country.code),["Z","A","B","C"]);
assert.deepEqual(selectedCountriesFirst(input,[]).map(country=>country.code),["A","B","C","Z"]);
console.log("Passed selected-first order, unselected order, deselection, Set selections and input immutability.");
