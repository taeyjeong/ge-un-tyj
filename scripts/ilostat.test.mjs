import assert from 'node:assert/strict';
import {parseIloQuery,iloSourceUrl,parseIloRows} from '../lib/ilostat.ts';
const query=parseIloQuery(new URLSearchParams('dataset=unemployment&countries=usa,jpn,USA&from=2020&to=2023&sex=both'));
assert.deepEqual(query.countries,['JPN','USA']);
const url=iloSourceUrl(query);
assert.equal(url.origin,'https://rplumber.ilo.org');
assert.equal(url.pathname,'/data/indicator');
assert.equal(url.searchParams.get('ref_area'),'JPN+USA');
assert.equal(url.searchParams.get('sex'),'SEX_F+SEX_M');
assert.equal(url.searchParams.get('classif1'),'AGE_YTHADULT_YGE15');
assert.equal(url.searchParams.get('timefrom'),'2020');
assert.equal(url.searchParams.get('timeto'),'2023');
assert.equal(url.searchParams.get('type'),'both');
assert.equal(url.searchParams.get('format'),'.json');
assert.equal(iloSourceUrl({...query,dataset:'women-management'}).searchParams.has('sex'),false);
assert.equal(iloSourceUrl({...query,dataset:'hourly-earnings'}).searchParams.get('id'),'EAR_EHRA_SEX_NB_A');
for(const params of ['dataset=arbitrary','countries=','countries=https://example.com','from=2024&to=2020','from=2020.5','sex=unknown','from=1900&to=2100'])assert.throws(()=>parseIloQuery(new URLSearchParams(params)));
assert.throws(()=>parseIloQuery(new URLSearchParams({countries:Array.from({length:61},(_,i)=>'A'+String.fromCharCode(65+Math.floor(i/26))+String.fromCharCode(65+i%26)).join(',')})));
const rows=[{ref_area:'JPN',time:'2023',obs_value:0,'source.label':'Survey'},{ref_area:'USA',time:'2022',obs_value:null}];
assert.deepEqual(parseIloRows(rows),rows);
assert.deepEqual(parseIloRows([]),[]);
for(const value of [{error:'Bad request'},[{time:'2023'}],[{obs_value:'abc'}],[{obs_value:Infinity}],[{obs_value:2,nested:{value:1}}]])assert.throws(()=>parseIloRows(value));
console.log('Passed ILO query validation, source URL filters, indicator allowlist, exact null/zero handling and upstream response validation.');
